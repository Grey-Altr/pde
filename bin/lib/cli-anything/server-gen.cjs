'use strict';

/**
 * server-gen.cjs — MCP server CJS file generator
 *
 * Generates a self-contained CJS MCP server file from a capability model.
 * The generated server uses stdio transport and registers one tool per capability.
 */

const path = require('path');
const fs = require('fs');

/**
 * Generate the source code for a self-contained MCP server.
 *
 * @param {object} model - CapabilityModel with meta and capabilities
 * @param {string} [sdkBasePath] - Absolute path to @modelcontextprotocol/sdk/dist/cjs
 * @returns {string} Valid CJS JavaScript source
 */
function generateServerSource(model, sdkBasePath) {
  const { meta, capabilities } = model;

  // Default SDK path relative to project root
  const effectiveSdkBase =
    sdkBasePath ||
    path.join(
      __dirname,
      '../../../packages/pde-mcp-server/node_modules/@modelcontextprotocol/sdk/dist/cjs'
    );

  const safeSdkBase = JSON.stringify(effectiveSdkBase);
  const safeBinary = JSON.stringify(meta.source);
  const safeServerName = JSON.stringify(meta.source);
  const timestamp = new Date().toISOString();

  // Build tool registrations for each capability
  const toolRegistrations = capabilities.map((cap) => generateToolRegistration(cap)).join('\n\n');

  return `// Auto-generated by /pde:wrap
// Binary: ${meta.source}
// Generated: ${timestamp}
'use strict';

const path = require('path');
const { spawnSync } = require('child_process');

const SDK_BASE = ${safeSdkBase};
const { McpServer } = require(path.join(SDK_BASE, 'server/mcp.js'));
const { StdioServerTransport } = require(path.join(SDK_BASE, 'server/stdio.js'));

const BINARY = ${safeBinary};
const DRY_RUN = process.argv.includes('--dry-run');

const server = new McpServer({ name: ${safeServerName}, version: '1.0.0' });

${toolRegistrations}

async function main() {
  const transport = new StdioServerTransport();
  await server.connect(transport);
}

main().catch(err => {
  process.stderr.write(err.message + '\\n');
  process.exit(1);
});
`;
}

/**
 * Generate the registerTool call for a single capability.
 *
 * @param {object} cap - Capability object
 * @returns {string} JavaScript source for registering one tool
 */
function generateToolRegistration(cap) {
  const safeName = JSON.stringify(cap.name);
  const safeDescription = JSON.stringify(cap.description || '');

  // Build inputSchema with useJson always included
  const baseProperties = {
    useJson: { type: 'boolean', description: 'Append --json flag to command' },
  };

  // Merge in any capability-specific properties (excluding useJson to avoid duplicate)
  const capProperties =
    cap.inputSchema && cap.inputSchema.properties ? cap.inputSchema.properties : {};
  const mergedProperties = Object.assign({}, baseProperties, capProperties);
  // Ensure useJson is always present
  mergedProperties.useJson = { type: 'boolean', description: 'Append --json flag to command' };

  const safeInputSchema = JSON.stringify({
    type: 'object',
    properties: mergedProperties,
  });

  // Subcommand path for the tool handler
  const subcommandPath =
    cap.extensions && cap.extensions.subcommandPath
      ? cap.extensions.subcommandPath
      : cap.path
      ? cap.path.split(' ').slice(1)
      : [];
  const safeSubcommandPath = JSON.stringify(subcommandPath);

  return `server.registerTool(
  ${safeName},
  {
    description: ${safeDescription},
    inputSchema: ${safeInputSchema},
    annotations: { readOnlyHint: false },
  },
  async (input) => {
    const args = ${safeSubcommandPath}.slice();
    if (input.useJson) args.push('--json');
    for (const [key, val] of Object.entries(input)) {
      if (key === 'useJson') continue;
      if (val !== undefined && val !== null && val !== false) {
        args.push('--' + key);
        if (val !== true) args.push(String(val));
      }
    }
    if (DRY_RUN) {
      return { content: [{ type: 'text', text: JSON.stringify({ dryRun: true, command: [BINARY, ...args] }) }] };
    }
    const r = spawnSync(BINARY, args, { encoding: 'utf8', timeout: 30000 });
    let data;
    try { data = JSON.parse(r.stdout); } catch { data = { stdout: (r.stdout || '').trim(), stderr: (r.stderr || '').trim(), exitCode: r.status ?? -1 }; }
    return { content: [{ type: 'text', text: JSON.stringify(data) }] };
  }
);`;
}

/**
 * Write a generated MCP server to disk.
 *
 * @param {string} outputDir - Directory to write server.cjs
 * @param {object[]} capabilities - Array of capability objects
 * @param {object} meta - Capability model meta object
 * @param {string} projectRoot - Absolute path to project root
 * @returns {string} Path to the written server.cjs file
 */
function writeServer(outputDir, capabilities, meta, projectRoot) {
  const sdkBasePath = path.join(
    projectRoot,
    'packages/pde-mcp-server/node_modules/@modelcontextprotocol/sdk/dist/cjs'
  );
  const source = generateServerSource({ meta, capabilities }, sdkBasePath);
  fs.mkdirSync(outputDir, { recursive: true });
  const outputPath = path.join(outputDir, 'server.cjs');
  fs.writeFileSync(outputPath, source, 'utf8');
  return outputPath;
}

module.exports = { generateServerSource, writeServer };
