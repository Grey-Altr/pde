'use strict';

/**
 * cad.cjs -- CadQuery parametric CAD generation module.
 *
 * Provides:
 *   - generateCAD()        -- Orchestrate CadQuery script generation, execution, validation, and asset storage
 *   - validateStep()       -- Validate a STEP file has the ISO-10303-21 header
 *   - checkCadQuery()      -- Detect if CadQuery is importable in Python env
 *   - getPythonVersion()   -- Return { major, minor } from python --version
 *   - saveCADAsset()       -- Write .step + .cq.py + .meta.json triple to assets dir
 *   - runCadScript()       -- Execute a CadQuery Python script via subprocess
 *
 * Requirements: TRD-06, TRD-07
 * User setup: CADQUERY_PYTHON env var pointing to python3 in CadQuery venv
 */

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const os = require('os');

const PYTHON_BIN_KEY = 'CADQUERY_PYTHON';
const DEFAULT_PYTHON = 'python3';
const SUBPROCESS_TIMEOUT = 60000;
const INSTALL_MSG =
  'CadQuery not found. Install:\n' +
  '  python3.11 -m venv ~/cadquery-env\n' +
  '  source ~/cadquery-env/bin/activate\n' +
  '  pip install cadquery\n' +
  '  export CADQUERY_PYTHON=~/cadquery-env/bin/python3';

function checkCadQuery(pythonBin, _execFn) {
  const execFn = _execFn || execFileSync;
  try {
    execFn(pythonBin, ['-c', 'import cadquery'], { encoding: 'utf8', timeout: 10000 });
    return true;
  } catch (_e) {
    return false;
  }
}

function getPythonVersion(pythonBin, _execFn) {
  const execFn = _execFn || execFileSync;
  try {
    const output = execFn(pythonBin, ['--version'], { encoding: 'utf8', timeout: 5000 });
    const m = String(output).match(/Python (\d+)\.(\d+)/);
    if (!m) return null;
    return { major: +m[1], minor: +m[2] };
  } catch (_e) {
    return null;
  }
}

function validateStep(filePath) {
  if (!fs.existsSync(filePath)) {
    return { valid: false, reason: 'file does not exist' };
  }
  const stat = fs.statSync(filePath);
  if (stat.size === 0) {
    return { valid: false, reason: 'file is empty' };
  }
  const header = fs.readFileSync(filePath, 'utf8').slice(0, 50);
  if (!header.includes('ISO-10303-21')) {
    return { valid: false, reason: 'missing ISO-10303-21 header' };
  }
  return { valid: true, size: fs.statSync(filePath).size };
}

function saveCADAsset({ slug, stepPath, scriptContent, params, assetsDir }) {
  const baseDir = assetsDir || require('./assets.cjs').THREE_D_DIR;
  fs.mkdirSync(baseDir, { recursive: true });
  const timestamp = Date.now();
  const stepDest = path.join(baseDir, slug + '-' + timestamp + '.step');
  const scriptDest = path.join(baseDir, slug + '-' + timestamp + '.cq.py');
  const metaDest = path.join(baseDir, slug + '-' + timestamp + '.meta.json');
  fs.copyFileSync(stepPath, stepDest);
  fs.writeFileSync(scriptDest, scriptContent);
  const meta = {
    source_script: path.relative(process.cwd(), scriptDest),
    params: params || {},
    timestamp: new Date(timestamp).toISOString(),
    file_size: fs.statSync(stepDest).size,
    step_version: 'ISO-10303-21',
    slug,
    step_path: path.relative(process.cwd(), stepDest),
  };
  fs.writeFileSync(metaDest, JSON.stringify(meta, null, 2));
  return { stepPath: stepDest, metaPath: metaDest, scriptPath: scriptDest, meta };
}

function runCadScript({ pythonBin, scriptContent, outputStepPath, _execFn }) {
  const execFn = _execFn || execFileSync;
  const tmpScript = path.join(os.tmpdir(), 'pde-cad-' + Date.now() + '.py');
  try {
    fs.writeFileSync(tmpScript, scriptContent);
    execFn(pythonBin, [tmpScript, outputStepPath], {
      encoding: 'utf8',
      timeout: SUBPROCESS_TIMEOUT,
      cwd: process.cwd(),
    });
  } finally {
    if (fs.existsSync(tmpScript)) {
      fs.unlinkSync(tmpScript);
    }
  }
}

function generateScript(description) {
  return [
    '# ' + (description || 'CadQuery parametric model'),
    '# Generated by Platform Development Engine (PDE)',
    'import cadquery as cq',
    'import sys',
    '',
    'PARAMS = {',
    '    "length": 80.0,',
    '    "width": 50.0,',
    '    "height": 25.0',
    '}',
    '',
    'result = cq.Workplane("XY").box(PARAMS["length"], PARAMS["width"], PARAMS["height"])',
    '',
    'output_path = sys.argv[1] if len(sys.argv) > 1 else "output.step"',
    'cq.exporters.export(result, output_path, exportType="STEP")',
    'print(f"STEP exported: {output_path}")',
  ].join('\n') + '\n';
}

async function generateCAD({ description, slug, assetsDir, _execFn, _scriptContent }) {
  const pythonBin = process.env[PYTHON_BIN_KEY] || DEFAULT_PYTHON;
  if (!checkCadQuery(pythonBin, _execFn)) {
    throw new Error(INSTALL_MSG);
  }
  const ver = getPythonVersion(pythonBin, _execFn);
  if (ver && (ver.major < 3 || (ver.major === 3 && ver.minor < 10))) {
    throw new Error(
      'Python 3.10+ required for CadQuery, found ' + ver.major + '.' + ver.minor
    );
  }
  const scriptContent = _scriptContent || generateScript(description);
  const tmpStep = path.join(os.tmpdir(), 'pde-cad-' + Date.now() + '.step');
  try {
    runCadScript({ pythonBin, scriptContent, outputStepPath: tmpStep, _execFn });
    const v = validateStep(tmpStep);
    if (!v.valid) {
      throw new Error('STEP validation failed: ' + v.reason);
    }
    const params = {};
    const paramsMatch = scriptContent.match(/PARAMS\s*=\s*\{([^}]+)\}/);
    if (paramsMatch) {
      const paramStr = paramsMatch[1];
      const paramRegex = /["'](\w+)["']\s*:\s*([\d.]+)/g;
      let m;
      while ((m = paramRegex.exec(paramStr)) !== null) {
        params[m[1]] = parseFloat(m[2]);
      }
    }
    const result = saveCADAsset({
      slug: slug || 'cad-model',
      stepPath: tmpStep,
      scriptContent,
      params,
      assetsDir,
    });
    return result;
  } finally {
    if (fs.existsSync(tmpStep)) {
      fs.unlinkSync(tmpStep);
    }
  }
}

module.exports = { generateCAD, validateStep, checkCadQuery, getPythonVersion, saveCADAsset, runCadScript };
